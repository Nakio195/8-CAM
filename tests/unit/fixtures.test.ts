import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";

const FIXTURES_DIR = join(import.meta.dirname, "..", "fixtures");

function readFixture(name: string): string
{
    return readFileSync(join(FIXTURES_DIR, name), "utf8");
}

// Guards the reference files used by the parser (J2) and FlatCAM comparison (J6, J9) tests
describe("reference fixtures", () =>
{
    it("contains the Proteus bottom copper Gerber X2 file", () =>
    {
        const gerber = readFixture("proteus/ftdi-max-bottom-copper.gbr");
        expect(gerber).toContain("%TF.FileFunction,Copper,L2,Bot*%");
        expect(gerber).toContain("%FSLAX45Y45*%");
        expect(gerber).toContain("%MOMM*%");
        expect(gerber.trimEnd().endsWith("M02*")).toBe(true);
    });

    it("contains the matching FlatCAM Plus isolation G-code", () =>
    {
        const gcode = readFixture("proteus/ftdi-max-bottom-copper.flatcam-iso.cnc");
        expect(gcode).toContain("(G-code generated by FlatCAM Plus");
        expect(gcode).toContain("(TOOL DIAMETER: 0.2072 mm)");
        expect(gcode).toContain("(Preprocessor Geometry: default)");
    });
});
